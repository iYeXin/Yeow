#!/usr/bin/env node
// 由 build.mjs 调用：把 native/polyfill/js/*.js 生成为 native/polyfill/js.generated.h
// （C 字符串字面量），避免在 C 源码中手工内联 JS。
//
// 命名约定：<file>.js -> <FILE>_JS（非字母数字转为下划线、大写），例如
// text_codec.js -> TEXT_CODEC_JS。
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JS_DIR = join(ROOT, 'native', 'polyfill', 'js');
const OUT = join(ROOT, 'native', 'polyfill', 'js.generated.h');

const cEscape = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const symbol = (file) => file.replace(/\.js$/, '').replace(/[^A-Za-z0-9]/g, '_').toUpperCase() + '_JS';

const files = readdirSync(JS_DIR).filter((f) => f.endsWith('.js')).sort();
if (files.length === 0) {
  console.error(`[gen-polyfill] no .js under ${JS_DIR}`);
  process.exit(1);
}

let out = '/* AUTO-GENERATED by quickjs-wrapper/scripts/gen-polyfill.mjs — do not edit.\n'
  + ' * Source: quickjs-wrapper/native/polyfill/js/*.js */\n'
  + '#ifndef YEOW_POLYFILL_JS_GENERATED_H\n#define YEOW_POLYFILL_JS_GENERATED_H\n\n';

for (const f of files) {
  const src = readFileSync(join(JS_DIR, f), 'utf8').replace(/\r\n?/g, '\n');
  const lines = src.split('\n');
  if (lines[lines.length - 1] === '') lines.pop();
  out += `static const char ${symbol(f)}[] =\n`;
  out += lines.map((l) => `    "${cEscape(l)}\\n"`).join('\n');
  out += ';\n\n';
}

out += '#endif /* YEOW_POLYFILL_JS_GENERATED_H */\n';
writeFileSync(OUT, out);
console.log(`[gen-polyfill] ${files.length} file(s) -> ${OUT}`);
